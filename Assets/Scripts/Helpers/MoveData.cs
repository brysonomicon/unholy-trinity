using System;
using System.Collections.Generic;
using UnholyTrinity.Hex;

namespace Helpers
{
    /// <summary>
    /// A struct to help keep the common function we want for moving things encapsulated.
    /// </summary>
    public struct MoveData : IEquatable<MoveData>
    {
        private readonly IEnumerator<(int remainingMoves, HexCoord currentPos)> _moveEnumerator;

        // [CB] Ratios are calculated and used to check if
        // something should move on a frame or not.
        private float _baseRatio;
        private float _currentRatio;
        public int RemainingMoves => _moveEnumerator.Current.Item1;
        public bool CanMove => RemainingMoves > 0;
        public bool ShouldMove => _currentRatio >= 1;

        public MoveData(
            IEnumerator<(int, HexCoord)> startingData,
            float ratio = 1f
        )
        {
            _currentRatio = 0;
            _baseRatio = ratio;
            _moveEnumerator = startingData;
            startingData.MoveNext();
        }

        public void IncrementRatio()
        {
            _currentRatio += _baseRatio;
        }

        public void SetBaseRatio(float ratio)
        {
            _baseRatio = ratio;
        }

        public bool MoveNext()
        {
            _currentRatio = _baseRatio;
            _moveEnumerator.MoveNext();
            return CanMove;
        }

        // [CB] Rider autogenerated the equality stuff.
        public bool Equals(MoveData other)
        {
            return Equals(_moveEnumerator, other._moveEnumerator);
        }

        public override bool Equals(object obj)
        {
            return obj is MoveData other && Equals(other);
        }

        public override int GetHashCode()
        {
            return HashCode.Combine(_moveEnumerator, _baseRatio,
                _currentRatio);
        }
    }
}