using System;
using UnholyTrinity.Hex;
using UnholyTrinity.Hex.Interfaces;
using UnityEngine;
using UnityEngine.Assertions;

namespace UnholyTrinity.Managers
{
    /// <summary>
    /// A struct to help keep the common function we want for moving things encapsulated.
    /// </summary>
    public class MoveData : IEquatable<MoveData>
    {
        // [CB] Ratios are calculated and used to check if
        // something should move on a frame or not.
        private float BaseRatio { get; set; }
        private float CurrentRatio { get; set; }
        public int RemainingMoves => Mover.RemainingStepCount;
        public bool CanMove => Mover.CanMove;
        public bool ShouldMove => Mover.CanMove && CurrentRatio >= 1;
        private HexCoord Coord => Mover.Coord;

        public IMovable Mover { get; }

        public MoveData(IMovable mover, float ratio = 1f
        )
        {
            Mover = mover;
            CurrentRatio = 0;
            BaseRatio = ratio;
        }

        public void IncrementRatio()
        {
            CurrentRatio += BaseRatio;
        }

        public void SetBaseRatio(float ratio)
        {
            BaseRatio = ratio;
            CurrentRatio = 0;
        }

        public void MoveNext()
        {
            CurrentRatio = 0;
            Mover.Move();
        }

        // [CB] Rider autogenerated the equality stuff.
        public bool Equals(MoveData other)
        {
            return other != null && Equals(Mover, other.Mover);
        }

        public override bool Equals(object obj)
        {
            return obj is MoveData other && Equals(other);
        }

        public override int GetHashCode() => HashCode.Combine(Mover, Coord,
            RemainingMoves, CanMove, ShouldMove);
    }
}
